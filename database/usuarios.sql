USE mazmorra;
CREATE TABLE IF NOT EXISTS users (
 id CHAR(32) PRIMARY KEY, name VARCHAR(80) NOT NULL,
 email VARCHAR(200) NOT NULL UNIQUE, contact VARCHAR(200) NOT NULL,
 password_hash VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS user_reservations (
 reservation_id VARCHAR(80) PRIMARY KEY, user_id CHAR(32) NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id),
 FOREIGN KEY(reservation_id) REFERENCES reservations(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
